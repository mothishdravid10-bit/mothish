package com.example.data.model

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey

@Entity(
    tableName = "users",
    indices = [Index(value = ["email"], unique = true)]
)
data class User(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val name: String,
    val email: String,
    val passwordHash: String,
    val companyName: String = "My Enterprise",
    val gstin: String = "",
    val stateCode: String = "27",
    val stateName: String = "Maharashtra",
    val createdAt: Long = System.currentTimeMillis()
)

enum class AccountCategory {
    ASSET,
    LIABILITY,
    EQUITY,
    INCOME,
    EXPENSE
}

@Entity(tableName = "accounts")
data class Account(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val userId: Long = 1,
    val code: String,
    val name: String,
    val category: AccountCategory,
    val subcategory: String,
    val openingBalance: Double = 0.0,
    val currentBalance: Double = 0.0,
    val isSystem: Boolean = false,
    val description: String = ""
)

enum class PartyType {
    CUSTOMER,
    SUPPLIER
}

@Entity(tableName = "parties")
data class Party(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val userId: Long = 1,
    val name: String,
    val type: PartyType,
    val phone: String = "",
    val email: String = "",
    val address: String = "",
    val gstin: String = "",
    val stateCode: String = "27", // Default Maharashtra (or user state)
    val stateName: String = "Maharashtra",
    val openingBalance: Double = 0.0,
    val outstandingAmount: Double = 0.0,
    val isActive: Boolean = true
)

@Entity(tableName = "products")
data class Product(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val userId: Long = 1,
    val name: String,
    val codeSku: String,
    val category: String,
    val purchasePrice: Double,
    val salesPrice: Double,
    val gstRate: Double = 18.0, // 0, 5, 12, 18, 28
    val hsnCode: String = "",
    val currentStock: Double = 0.0,
    val minStockAlert: Double = 5.0,
    val unit: String = "Pcs"
)

enum class InvoiceStatus {
    PAID,
    UNPAID,
    PARTIAL
}

@Entity(tableName = "sales_invoices")
data class SalesInvoice(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val userId: Long = 1,
    val invoiceNumber: String,
    val customerId: Long,
    val customerName: String,
    val date: Long = System.currentTimeMillis(),
    val subtotal: Double,
    val cgst: Double = 0.0,
    val sgst: Double = 0.0,
    val igst: Double = 0.0,
    val totalAmount: Double,
    val isInterstate: Boolean = false,
    val status: InvoiceStatus = InvoiceStatus.UNPAID,
    val paymentMode: String = "CREDIT", // CASH, BANK, CREDIT, UPI
    val notes: String = ""
)

@Entity(tableName = "sales_invoice_items")
data class SalesInvoiceItem(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val invoiceId: Long,
    val productId: Long,
    val productName: String,
    val quantity: Double,
    val unitRate: Double,
    val discountPercent: Double = 0.0,
    val gstRate: Double = 18.0,
    val taxableAmount: Double,
    val taxAmount: Double,
    val totalAmount: Double
)

@Entity(tableName = "purchase_bills")
data class PurchaseBill(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val userId: Long = 1,
    val billNumber: String,
    val supplierId: Long,
    val supplierName: String,
    val date: Long = System.currentTimeMillis(),
    val subtotal: Double,
    val cgst: Double = 0.0,
    val sgst: Double = 0.0,
    val igst: Double = 0.0,
    val totalAmount: Double,
    val isInterstate: Boolean = false,
    val status: InvoiceStatus = InvoiceStatus.UNPAID,
    val paymentMode: String = "CREDIT",
    val notes: String = ""
)

@Entity(tableName = "purchase_bill_items")
data class PurchaseBillItem(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val billId: Long,
    val productId: Long,
    val productName: String,
    val quantity: Double,
    val unitRate: Double,
    val gstRate: Double = 18.0,
    val taxableAmount: Double,
    val taxAmount: Double,
    val totalAmount: Double
)

@Entity(tableName = "journal_entries")
data class JournalEntry(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val userId: Long = 1,
    val entryNumber: String,
    val date: Long = System.currentTimeMillis(),
    val reference: String = "",
    val narration: String,
    val totalDebit: Double,
    val totalCredit: Double,
    val isAutoGenerated: Boolean = false,
    val sourceModule: String = "JOURNAL" // SALES, PURCHASE, RECEIPT, PAYMENT, MANUAL
)

@Entity(tableName = "journal_entry_lines")
data class JournalEntryLine(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val journalEntryId: Long,
    val accountId: Long,
    val accountName: String,
    val isDebit: Boolean,
    val amount: Double,
    val description: String = ""
)

enum class VoucherType {
    RECEIPT,
    PAYMENT
}

@Entity(tableName = "payment_vouchers")
data class PaymentVoucher(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val userId: Long = 1,
    val voucherNumber: String,
    val type: VoucherType,
    val partyId: Long,
    val partyName: String,
    val accountId: Long, // Cash or Bank account
    val accountName: String,
    val amount: Double,
    val paymentMode: String = "BANK", // CASH, BANK, UPI, CHEQUE
    val date: Long = System.currentTimeMillis(),
    val reference: String = "",
    val notes: String = ""
)

enum class ReminderStatus {
    PENDING,
    SETTLED,
    OVERDUE
}

@Entity(tableName = "reminders")
data class PaymentReminder(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val userId: Long = 1,
    val title: String,
    val partyId: Long,
    val partyName: String,
    val amount: Double,
    val dueDate: Long,
    val type: PartyType,
    val status: ReminderStatus = ReminderStatus.PENDING,
    val notes: String = ""
)

@Entity(tableName = "company_settings")
data class CompanySettings(
    @PrimaryKey val userId: Long = 1,
    val companyName: String = "My Enterprise",
    val tradeName: String = "ZENO AI",
    val gstin: String = "",
    val address: String = "Mumbai, Maharashtra",
    val phone: String = "",
    val email: String = "",
    val stateCode: String = "27",
    val stateName: String = "Maharashtra",
    val financialYear: String = "2026-2027",
    val baseCurrency: String = "INR",
    val currencySymbol: String = "₹",
    val invoicePrefix: String = "INV-26/",
    val billPrefix: String = "BILL-26/",
    val receiptPrefix: String = "RCP-26/",
    val paymentPrefix: String = "PAY-26/"
)
